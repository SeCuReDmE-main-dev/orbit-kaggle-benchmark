"""Build the unexecuted successor deterministically. --check never writes files."""
from __future__ import annotations

import argparse
import ast
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = "pilot/native-pass-fail-hardened"
PARENT = "pilot/native-pass-fail"
PARENT_MANIFEST_SHA256 = "3b141b8760525c312e694cee3da55a0fdc3e2ef7507ad146dac97a8ef0d8815b"
CAMPAIGN_ID = "orbit-native-pass-fail-hardening-20261008-v1"
MAIN_TASK = "orbit_native_pass_fail_hardened"
INPUT_NAMES = ("PUBLIC", "GOLD", "PROMPT", "ENGINE_BYTES", "ENGINE_SHA256")


def sha(data):
    return hashlib.sha256(data).hexdigest()


def encoded_json(value):
    return (json.dumps(value, indent=2, ensure_ascii=True) + "\n").encode("utf-8")


def expected_artifacts(root=ROOT):
    """Read trusted authored inputs; return generated bytes without importing any task."""
    root = Path(root)
    parent_manifest_bytes = (root / PARENT / "manifest.json").read_bytes()
    if sha(parent_manifest_bytes) != PARENT_MANIFEST_SHA256:
        raise ValueError("Historical parent manifest changed")
    parent = json.loads(parent_manifest_bytes)
    for name, expected in parent["files"].items():
        if sha((root / PARENT / name).read_bytes()) != expected:
            raise ValueError("Historical parent bytes changed: " + name)
    historical = (root / PARENT / "task.py").read_text(encoding="utf-8")
    tree = ast.parse(historical)
    assignments = {node.targets[0].id: node for node in tree.body
                   if isinstance(node, ast.Assign) and len(node.targets) == 1
                   and isinstance(node.targets[0], ast.Name)}
    frozen_source = "\n".join(ast.get_source_segment(historical, assignments[name]) for name in INPUT_NAMES)
    prompt = ast.literal_eval(assignments["PROMPT"].value)
    engine = base64.b64decode(ast.literal_eval(assignments["ENGINE_BYTES"].value.args[0]), validate=True)
    public = ast.literal_eval(assignments["PUBLIC"].value.args[0])
    gold = ast.literal_eval(assignments["GOLD"].value.args[0])
    if sha(prompt.encode()) != parent["historicalPromptSha256"] or sha(engine) != parent["historicalEngineSha256"]:
        raise ValueError("Historical embedded input identity changed")
    directory = root / DIRECTORY
    contract_bytes = (directory / "contract.py").read_bytes()
    template_bytes = (directory / "task-template.py.in").read_bytes()
    contract = contract_bytes.decode("utf-8").rstrip("\n")
    template = template_bytes.decode("utf-8")
    for marker in ("# @FROZEN_INPUTS@", "# @CONTRACT@"):
        if template.count(marker) != 1:
            raise ValueError("Expected one template marker: " + marker)
    source = template.replace("# @FROZEN_INPUTS@", frozen_source).replace("# @CONTRACT@", contract)
    source = source.replace("\r\n", "\n").rstrip() + "\n"
    generated_tree = ast.parse(source)
    selected = [node for node in generated_tree.body if isinstance(node, ast.Assign)
                and any(isinstance(target, ast.Name) and target.id == "SELECTED_MODELS" for target in node.targets)]
    if len(selected) != 1 or ast.literal_eval(selected[0].value) != parent["models"]:
        raise ValueError("Selected models must exactly match the historical parent manifest")
    task = next(node for node in generated_tree.body if isinstance(node, ast.FunctionDef) and node.name == MAIN_TASK)
    if not isinstance(task.returns, ast.Name) or task.returns.id != "bool":
        raise ValueError("Native result must remain an explicit bool")
    functions = {node.name: ast.dump(node) for node in generated_tree.body if isinstance(node, (ast.FunctionDef, ast.ClassDef))}
    for node in ast.parse(contract).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and functions.get(node.name) != ast.dump(node):
            raise ValueError("Embedded contract differs: " + node.name)
    enabled = [node for node in generated_tree.body if isinstance(node, ast.Assign)
               and any(isinstance(target, ast.Name) and target.id == "RUN_MODELS" for target in node.targets)]
    if len(enabled) != 1 or ast.literal_eval(enabled[0].value) is not False:
        raise ValueError("Prepared notebook must have RUN_MODELS=False")
    cells = source.split("# %%\n")
    if cells[0] or len(cells) != 6:
        raise ValueError("Expected five generated code cells")
    markdown = ("# Orbit hardened native Boolean pilot\n\n"
                "Prepared and locally testable only. No Kaggle execution or publication is claimed. "
                "RUN_MODELS is False; model dispatch, native archive and task selection are disabled. "
                "A future execution needs a fresh free-quota check and separate authorization. "
                "The historical pilot and its receipts remain unchanged.\n")
    notebook = {"nbformat": 4, "nbformat_minor": 5,
                "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
                "cells": [{"id": "introduction", "cell_type": "markdown", "metadata": {}, "source": markdown}] +
                [{"id": "code-" + str(i), "cell_type": "code", "metadata": {}, "execution_count": None,
                  "outputs": [], "source": cell} for i, cell in enumerate(cells[1:], 1)]}
    result = {"task.py": source.encode("utf-8"), "orbit-native-pass-fail-hardened.ipynb": encoded_json(notebook)}
    manifest = {
        "format": "orbit-native-hardened-preparation-v1", "state": "prepared-not-executed",
        "campaignId": CAMPAIGN_ID, "mainTask": MAIN_TASK, "sourceDecoratorVersion": 1,
        "nativeResultType": "bool", "sdkVersion": "0.6.1", "models": parent["models"],
        "runModelsByDefault": False, "maxProviderAttemptsPerModel": 1, "maxAutomaticRetries": 0,
        "modelCallsDuringPreparation": 0, "nativeRunsExecuted": 0, "publishedOnKaggle": False,
        "parent": {"path": PARENT, "manifestSha256": PARENT_MANIFEST_SHA256, "sourceFiles": parent["files"]},
        "frozenInputs": {"promptSha256": sha(prompt.encode()), "engineSha256": sha(engine),
                         "publicSha256": sha(public.encode()), "goldSha256": sha(gold.encode()),
                         "jsonHashPolicy": "PUBLIC/GOLD hashes cover the exact UTF-8 JSON literal payload extracted from the parent AST."},
        "files": {"contract.py": sha(contract_bytes), "task-template.py.in": sha(template_bytes),
                  **{name: sha(data) for name, data in result.items()}},
        "builder": {"path": "tools/build_native_pilot_hardened.py",
                    "sha256": sha((root / "tools/build_native_pilot_hardened.py").read_bytes())},
        "localValidation": {"testCommand": "python -B -m unittest discover -s tests -p test_native_pilot_hardened.py",
                            "checkCommand": "python -B tools/build_native_pilot_hardened.py --check",
                            "resultReceipt": "local-validation.json",
                            "scope": "Pure local tests and byte/AST checks; not a model or engine benchmark."},
        "selfHashPolicy": "Manifest and local test receipt are excluded from files; the package catalog may hash them."
    }
    result["manifest.json"] = encoded_json(manifest)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare expected bytes without changing any file.")
    args = parser.parse_args()
    expected = expected_artifacts()
    directory = ROOT / DIRECTORY
    mismatches = []
    for name, data in expected.items():
        target = directory / name
        if args.check:
            if not target.is_file() or target.read_bytes() != data:
                mismatches.append(name)
        else:
            target.write_bytes(data)
    print(json.dumps({"state": "FAIL" if mismatches else "PASS", "mode": "check" if args.check else "build",
                      "generatedArtifacts": len(expected), "mismatches": mismatches,
                      "modelCalls": 0, "engineRuns": 0, "kaggleRuns": 0}))
    raise SystemExit(1 if mismatches else 0)


if __name__ == "__main__":
    main()
